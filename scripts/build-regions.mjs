// Writes public/js/regions.js: for each currency in use today, the countries and territories
// that use it, as region codes. Names come from Intl.DisplayNames at runtime, so the same
// table works in any language. Source: CLDR supplemental currency data (cldr-core).
//
// Run from the repo root: node scripts/build-regions.mjs
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { region } = require('cldr-core/supplemental/currencyData.json').supplemental.currencyData

// Region codes that aren't places a traveller would search for.
const SKIP = new Set(['ZZ', 'QO'])

const byCurrency = {}
for (const [code, history] of Object.entries(region)) {
  if (SKIP.has(code) || !/^[A-Z]{2}$/.test(code)) continue
  for (const entry of history) {
    const [currency, info] = Object.entries(entry)[0]
    if (info._to || info._tender === 'false') continue
    ;(byCurrency[currency] ??= []).push(code)
  }
}

// ISO 4217 codes start with the issuing country's code; list that one first.
const out = {}
for (const currency of Object.keys(byCurrency).sort()) {
  const regions = byCurrency[currency].sort()
  const home = currency.slice(0, 2)
  out[currency] = regions.includes(home) ? [home, ...regions.filter((r) => r !== home)] : regions
}

const body = Object.entries(out)
  .map(([c, r]) => `  ${c}: [${r.map((x) => `'${x}'`).join(', ')}],`)
  .join('\n')
writeFileSync(
  new URL('../public/js/regions.js', import.meta.url),
  `// Generated by scripts/build-regions.mjs from CLDR. Do not edit by hand.\n` +
    `// Countries and territories that use each currency today, home country first.\n` +
    `export const REGIONS = {\n${body}\n}\n`,
)
console.log(`regions.js: ${Object.keys(out).length} currencies`)
